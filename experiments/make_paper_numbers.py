"""
===============================================================================
FILE         : make_paper_numbers.py
PROJECT      : The Knowledge Lifecycle of Large Language Models
PURPOSE      : Turn counterfactual_summary.json into LaTeX, so that every number
               the manuscript quotes comes from the measurement rather than from
               a hand-typed digit that can drift.
TECH STACK   : Python 3 (standard library only)
AUTHORS      : Amey Thakur (https://github.com/Amey-Thakur)
               Sarvesh Talele (https://github.com/sarveshtalele)
REPOSITORY   : https://github.com/Amey-Thakur/LLM-KNOWLEDGE-LIFECYCLE
LICENSE      : CC BY 4.0
===============================================================================

Writes two files into preprint/:

  numbers.tex        one \newcommand per quoted figure
  results-table.tex  the per-model results table

The previous version of this paper quoted a figure that its own code had never
measured. Generating both from the data is the cheapest guard against that
happening again.
"""

import json
import pathlib

HERE = pathlib.Path(__file__).resolve().parent
OUT = HERE.parent / "preprint"

SHORT = {
    "gpt2": "GPT-2",
    "gpt2-medium": "GPT-2 medium",
    "gpt2-large": "GPT-2 large",
    "Qwen/Qwen2.5-0.5B-Instruct": "Qwen2.5-0.5B-Instruct",
    "TinyLlama/TinyLlama-1.1B-Chat-v1.0": "TinyLlama-1.1B-Chat",
    "Qwen/Qwen2.5-1.5B-Instruct": "Qwen2.5-1.5B-Instruct",
}
ORDER = list(SHORT)


def main():
    data = json.loads((HERE / "counterfactual_summary.json").read_text(encoding="utf-8"))
    m = data["models"]

    lines = ["% Generated by experiments/make_paper_numbers.py. Do not edit."]

    def cmd(name, value):
        lines.append(f"\\newcommand{{\\{name}}}{{{value}}}")

    cmd("NRows", f"{data['n_rows']:,}".replace(",", "{,}"))
    cmd("NDoc", data["n_rows"] // 2)  # conditions with the document present
    cmd("NModels", len(m))
    cmd("OverallUpdate", data["overall_update_pct"])
    cmd("OverallStale", data["overall_stale_pct"])
    cmd("MedianPhrasingSpread", data["median_phrasing_spread"])
    cmd("ProbOverTen", data["prob_over_10pct"])
    cmd("ProbOverTenNotTop", data["prob_over_10pct_not_top1"])
    cmd("ProbOverTenNotTopPct", data["prob_over_10pct_not_top1_pct"])

    knows = [m[k]["knows_no_doc_pct"] for k in ORDER if k in m]
    cmd("KnowsMin", min(knows))
    cmd("KnowsMax", max(knows))
    cmd("PerModel", m["gpt2"]["n"])

    # The conflict-conditional figures, which are the ones the paper leads on.
    cmd("NConflict", data["n_conflict_total"])
    cmd("AdoptConflict", data["adopt_in_conflict_overall_pct"])
    cmd("KeepConflict", data["keep_in_conflict_overall_pct"])
    adopts = [m[k]["adopt_in_conflict_pct"] for k in ORDER if k in m]
    cmd("AdoptMin", min(adopts))
    cmd("AdoptMax", max(adopts))
    cmd("AdoptQwenSmall", m["Qwen/Qwen2.5-0.5B-Instruct"]["adopt_in_conflict_pct"])
    cmd("AdoptQwenLarge", m["Qwen/Qwen2.5-1.5B-Instruct"]["adopt_in_conflict_pct"])
    cmd("AdoptTiny", m["TinyLlama/TinyLlama-1.1B-Chat-v1.0"]["adopt_in_conflict_pct"])
    cmd("KeepTiny", m["TinyLlama/TinyLlama-1.1B-Chat-v1.0"]["keep_in_conflict_pct"])
    cmd("KnowsTiny", m["TinyLlama/TinyLlama-1.1B-Chat-v1.0"]["knows_no_doc_pct"])
    cmd("KeepQwenLarge", m["Qwen/Qwen2.5-1.5B-Instruct"]["keep_in_conflict_pct"])
    cmd("NConflictTiny", m["TinyLlama/TinyLlama-1.1B-Chat-v1.0"]["n_conflict"])
    cmd("MaxPhrasingSpread", max(m[k]["phrasing_spread"] for k in ORDER if k in m))
    qs = m["Qwen/Qwen2.5-0.5B-Instruct"]["update_by_phrasing"]
    cmd("QwenSmallBest", max(qs))
    cmd("QwenSmallWorst", min(qs))

    (OUT / "numbers.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")

    rows = []
    for k in ORDER:
        if k not in m:
            continue
        r = m[k]
        rows.append(
            f"{SHORT[k]} & {r['params_m']} & {r['knows_no_doc_pct']:.1f}\\% & "
            f"{r['n_conflict']} & {r['adopt_in_conflict_pct']:.1f}\\% & "
            f"{r['keep_in_conflict_pct']:.1f}\\% & "
            f"{r['phrasing_spread']:.1f} \\\\")

    table = "\n".join([
        r"\begin{table}[t]",
        r"\centering",
        r"\begin{tabular}{lrrrrrr}",
        r"\toprule",
        r"& Params & Knows & & Adopts & Keeps & Phrasing \\",
        r"Model & (M) & the fact & $n$ & the document & its own & spread \\",
        r"\midrule",
        *rows,
        r"\bottomrule",
        r"\end{tabular}",
        r"\caption{What each model does when a document contradicts it. "
        r"\emph{Knows the fact} is how often the true capital is the top-ranked "
        r"continuation with no document present, over \PerModel\ probe-phrasing "
        r"pairs. The remaining columns are restricted to the $n$ pairs where that "
        r"held, which are the cases in which a conflict actually exists: "
        r"\emph{adopts the document} and \emph{keeps its own} are how often the "
        r"counterfactual and the true answer respectively are top-ranked once the "
        r"document is supplied. They need not sum to 100, because a model may rank "
        r"a third token first. \emph{Phrasing spread} is the range of the adoption "
        r"rate across the three wordings, in percentage points. Knowing the fact "
        r"rises monotonically with parameter count; adopting the document does not.}",
        r"\label{tab:results}",
        r"\end{table}",
    ])
    (OUT / "results-table.tex").write_text(table + "\n", encoding="utf-8")

    print(f"wrote {OUT / 'numbers.tex'} ({len(lines) - 1} macros)")
    print(f"wrote {OUT / 'results-table.tex'} ({len(rows)} rows)")


if __name__ == "__main__":
    main()
